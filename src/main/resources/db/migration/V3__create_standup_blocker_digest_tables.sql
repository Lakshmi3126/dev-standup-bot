CREATE TABLE standup (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id BIGINT NOT NULL REFERENCES team(id),
    member_id BIGINT NOT NULL REFERENCES member(id),
    standup_date DATE NOT NULL,
    yesterday TEXT,
    today TEXT,
    blockers TEXT,
    submitted_at TIMESTAMP WITH TIME ZONE,
    status VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_standup_team_member_date
        UNIQUE (team_id, member_id, standup_date)
);

CREATE TABLE blocker (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES member(id),
    standup_id BIGINT NOT NULL REFERENCES standup(id),
    description TEXT NOT NULL,
    first_reported_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_reported_at TIMESTAMP WITH TIME ZONE NOT NULL,
    consecutive_days INTEGER NOT NULL,
    status VARCHAR(255) NOT NULL
);

CREATE TABLE digest_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id BIGINT NOT NULL REFERENCES team(id),
    digest_date DATE NOT NULL,
    status VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    sent_at TIMESTAMP WITH TIME ZONE,
    last_updated_at TIMESTAMP WITH TIME ZONE,
    slack_message_ts VARCHAR(255),
    update_count INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT uk_digest_team_date
        UNIQUE (team_id, digest_date)
);